/**
 * The fixed bot pool. Each persona is a different person, not a different prompt:
 * style quirks are applied in code (lib/bots/humanize.ts) as well as in the prompt,
 * so even a bland LLM line comes out in that person's voice.
 *
 * Server-only data. Never ship to the client.
 */
export interface Persona {
  /** Stable key used by the planner. Index in this array = pool index. */
  key: string;
  /** CometChat display name, typed the way this person would type it. */
  name: string;
  age: number;
  city: string;
  occupation: string;
  interests: string[];
  personality: string;
  typingStyle: string;
  quirks: string[];
  habits: string[];
  opinions: string[];
  language: "english" | "hinglish" | "mixed";
  /** 0..1: how much Hindi slips in when the room allows it. */
  hinglish: number;
  /** 0..1: likelihood of being picked to speak. */
  talkativeness: number;
  length: "terse" | "short" | "medium";
  lowercase: boolean;
  /** Chance of one transposed-letter typo per message. */
  typoRate: number;
  /** Chance of sending a "*fix" follow-up after a typo. */
  correctsTypos: number;
  /** Characters per second while "typing". */
  typingCps: number;
  /** How suspicious they are when voting (0..1). */
  paranoia: number;
  /** Reveal-only, public after REVEAL: "The sarcastic one". */
  tagline: string;
  /** Reveal-only: 2–3 short traits. Never prompt text. */
  traits: string[];
}

